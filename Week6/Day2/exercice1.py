# AVANT la modification du System Prompt
#
# Question :
# Quelle est la meilleure technologie pour développer
# une application web ?
#
# Réponse :
# React est la meilleure technologie pour développer
# une application web moderne.
#
# Observation :
# La réponse est directe, mais elle suppose que React
# est toujours le meilleur choix sans connaître les besoins
# du projet.


# APRÈS la modification du System Prompt
#
# Instructions ajoutées :
# - Donner des réponses courtes.
# - Utiliser un langage simple.
# - Poser une question de clarification si nécessaire.
# - Ne jamais inventer des informations ou des règles.
#
# Même question :
# Quelle est la meilleure technologie pour développer
# une application web ?
#
# Réponse :
# Cela dépend de votre projet.
# Cherchez-vous à développer une application simple
# ou une application web complexe ?
#
# Observation :
# La réponse est plus claire et demande une précision
# avant de proposer une solution.


# Comparaison :
# Avant : Réponse directe avec une supposition.
# Après : Réponse courte avec une question de clarification.

